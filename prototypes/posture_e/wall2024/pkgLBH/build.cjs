const fs=require("fs"),c=require("crypto");
const md5=x=>c.createHash("md5").update(x,"utf8").digest("hex");
const s=fs.readFileSync("revert_get_load_briefing_core.sql","utf8");
let n=s;
const decl="  v_bb_open int;\n  v_bb_urgent int;\n  v_bb_entries jsonb;\n  v_bb_ids jsonb;\n";
if(n.split(decl).length!==2) throw "decl";
n=n.replace(decl,"");
const a=n.indexOf("  -- BLACKBOARD SURFACING");
const endMark="    v_bb := jsonb_build_object('open_count', -1, 'note', 'blackboard unavailable — report this, do not ignore it');\n  END;\n";
const b=n.indexOf(endMark);
if(a<0||b<0||n.indexOf(endMark,b+1)>=0) throw "block";
const blk="  -- BLACKBOARD: retired as a working channel. The table stays as history; this briefing does not read it.\n  v_bb := jsonb_build_object('note', 'The Blackboard is history: it is no longer a working channel and this briefing does not read it. The table stays readable as a record (blackboard_read).');\n";
const old=n.slice(a,b+endMark.length);
n=n.slice(0,a)+blk+n.slice(b+endMark.length);
fs.writeFileSync("new_get_load_briefing_core.sql",n);
const src=x=>x.slice(x.indexOf("AS $function$")+13,x.lastIndexOf("$function$"));
console.log("old full",[...s].length,md5(s),"prosrc",[...src(s)].length,md5(src(s)));
console.log("new full",[...n].length,md5(n),"prosrc",[...src(n)].length,md5(src(n)));
console.log("delta",[...n].length-[...s].length,"removed block chars",[...old].length,"added",[...blk].length);
console.log("blackboard mentions in new:",(n.match(/blackboard/gi)||[]).length, "FROM blackboard:",/FROM\s+blackboard/i.test(n));
