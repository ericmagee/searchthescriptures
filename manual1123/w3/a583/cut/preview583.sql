-- 5. engine_manual_apply: refuses while the parts table holds a row; otherwise the live text unchanged
CREATE OR REPLACE FUNCTION public.engine_manual_apply(p_base_version integer, p_base_md5 text, p_pairs jsonb, p_expect_md5 text, p_expect_len integer, p_title text, p_summary text, p_log text, p_write boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE v_max int; v_txt text; v_pair jsonb; v_old text; v_new text; v_cnt int; v_i int := 0;
        v_counts jsonb := '[]'::jsonb; v_md5 text; v_len int; v_id bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM engine_manual_parts) THEN
    RETURN jsonb_build_object('success',false,'error','the engine manual is held in parts since version '
      || (SELECT min(version) FROM engine_manual_parts) || '; use engine_manual_part_apply');
  END IF;
  SELECT max(version) INTO v_max FROM engine_manual;
  IF p_base_version IS DISTINCT FROM v_max THEN
    RETURN jsonb_build_object('success',false,'error','base version '||coalesce(p_base_version::text,'null')||' is not the max version '||v_max);
  END IF;
  SELECT content INTO v_txt FROM engine_manual WHERE version = v_max ORDER BY id DESC LIMIT 1;
  IF md5(v_txt) IS DISTINCT FROM p_base_md5 THEN
    RETURN jsonb_build_object('success',false,'error','base md5 '||md5(v_txt)||' is not '||coalesce(p_base_md5,'null'));
  END IF;
  IF jsonb_typeof(p_pairs) IS DISTINCT FROM 'array' OR jsonb_array_length(p_pairs) = 0 THEN
    RETURN jsonb_build_object('success',false,'error','pairs must be a non-empty json array of {old,new}');
  END IF;
  FOR v_pair IN SELECT value FROM jsonb_array_elements(p_pairs) LOOP
    v_i := v_i + 1;
    v_old := v_pair->>'old'; v_new := v_pair->>'new';
    IF v_old IS NULL OR v_old = '' OR v_new IS NULL THEN
      RETURN jsonb_build_object('success',false,'error','pair '||v_i||' lacks old or new text','pair',v_i);
    END IF;
    v_cnt := (length(v_txt) - length(replace(v_txt, v_old, ''))) / length(v_old);
    v_counts := v_counts || to_jsonb(v_cnt);
    IF v_cnt <> 1 THEN
      RETURN jsonb_build_object('success',false,'error','pair '||v_i||': old text occurs '||v_cnt||' times, not once','pair',v_i,'counts',v_counts);
    END IF;
    v_txt := replace(v_txt, v_old, v_new);
  END LOOP;
  v_md5 := md5(v_txt); v_len := length(v_txt);
  IF NOT coalesce(p_write,false) THEN
    RETURN jsonb_build_object('success',true,'preview',true,'md5',v_md5,'length',v_len,'counts',v_counts,'base_version',v_max);
  END IF;
  IF v_md5 IS DISTINCT FROM p_expect_md5 OR v_len IS DISTINCT FROM p_expect_len THEN
    RETURN jsonb_build_object('success',false,'error','result md5 '||v_md5||' length '||v_len||' is not the expected '||coalesce(p_expect_md5,'null')||' / '||coalesce(p_expect_len::text,'null'));
  END IF;
  IF coalesce(btrim(p_title),'') = '' OR coalesce(btrim(p_summary),'') = '' OR coalesce(btrim(p_log),'') = '' THEN
    RETURN jsonb_build_object('success',false,'error','title, summary and log are required to write');
  END IF;
  INSERT INTO engine_manual (version, content, summary) VALUES (v_max + 1, v_txt, p_summary) RETURNING id INTO v_id;
  INSERT INTO engine_manual_log (version, entry_date, title, content, char_len)
    VALUES (v_max + 1, (now() at time zone 'America/Chicago')::date, p_title, p_log, v_len);
  RETURN jsonb_build_object('success',true,'written',true,'id',v_id,'version',v_max + 1,'md5',v_md5,'length',v_len,'counts',v_counts);
END; $function$;

-- 6. engine_manual_part_apply: the logic of engine_manual_apply on one part
CREATE OR REPLACE FUNCTION public.engine_manual_part_apply(p_part text, p_base_version integer, p_base_md5 text, p_pairs jsonb, p_expect_md5 text, p_expect_len integer, p_title text, p_summary text, p_log text, p_write boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE v_base record; v_max int; v_txt text; v_pair jsonb; v_old text; v_new text; v_cnt int; v_i int := 0;
        v_counts jsonb := '[]'::jsonb; v_md5 text; v_len int; v_id bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('engine_manual_version'));
  SELECT * INTO v_base FROM engine_manual_parts WHERE part = p_part ORDER BY version DESC LIMIT 1;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success',false,'error','no part '||coalesce(p_part,'null'));
  END IF;
  IF p_base_version IS DISTINCT FROM v_base.version THEN
    RETURN jsonb_build_object('success',false,'error','base version '||coalesce(p_base_version::text,'null')||' is not part '||p_part||'''s latest version '||v_base.version);
  END IF;
  v_txt := v_base.content;
  IF md5(v_txt) IS DISTINCT FROM p_base_md5 THEN
    RETURN jsonb_build_object('success',false,'error','base md5 '||md5(v_txt)||' is not '||coalesce(p_base_md5,'null'));
  END IF;
  IF jsonb_typeof(p_pairs) IS DISTINCT FROM 'array' OR jsonb_array_length(p_pairs) = 0 THEN
    RETURN jsonb_build_object('success',false,'error','pairs must be a non-empty json array of {old,new}');
  END IF;
  FOR v_pair IN SELECT value FROM jsonb_array_elements(p_pairs) LOOP
    v_i := v_i + 1;
    v_old := v_pair->>'old'; v_new := v_pair->>'new';
    IF v_old IS NULL OR v_old = '' OR v_new IS NULL THEN
      RETURN jsonb_build_object('success',false,'error','pair '||v_i||' lacks old or new text','pair',v_i);
    END IF;
    v_cnt := (length(v_txt) - length(replace(v_txt, v_old, ''))) / length(v_old);
    v_counts := v_counts || to_jsonb(v_cnt);
    IF v_cnt <> 1 THEN
      RETURN jsonb_build_object('success',false,'error','pair '||v_i||': old text occurs '||v_cnt||' times, not once','pair',v_i,'counts',v_counts);
    END IF;
    v_txt := replace(v_txt, v_old, v_new);
  END LOOP;
  SELECT greatest((SELECT max(version) FROM engine_manual), (SELECT max(version) FROM engine_manual_parts)) INTO v_max;
  v_md5 := md5(v_txt); v_len := length(v_txt);
  IF NOT coalesce(p_write,false) THEN
    RETURN jsonb_build_object('success',true,'preview',true,'part',p_part,'md5',v_md5,'length',v_len,'counts',v_counts,'base_version',v_base.version,'next_version',v_max + 1);
  END IF;
  IF v_md5 IS DISTINCT FROM p_expect_md5 OR v_len IS DISTINCT FROM p_expect_len THEN
    RETURN jsonb_build_object('success',false,'error','result md5 '||v_md5||' length '||v_len||' is not the expected '||coalesce(p_expect_md5,'null')||' / '||coalesce(p_expect_len::text,'null'));
  END IF;
  IF coalesce(btrim(p_title),'') = '' OR coalesce(btrim(p_summary),'') = '' OR coalesce(btrim(p_log),'') = '' THEN
    RETURN jsonb_build_object('success',false,'error','title, summary and log are required to write');
  END IF;
  INSERT INTO engine_manual_parts (part, order_index, title, version, content, summary)
    VALUES (p_part, v_base.order_index, v_base.title, v_max + 1, v_txt, p_summary) RETURNING id INTO v_id;
  INSERT INTO engine_manual_log (version, entry_date, title, content, char_len, part)
    VALUES (v_max + 1, (now() at time zone 'America/Chicago')::date, p_title, p_log, v_len, p_part);
  RETURN jsonb_build_object('success',true,'written',true,'id',v_id,'part',p_part,'version',v_max + 1,'md5',v_md5,'length',v_len,'counts',v_counts);
END; $function$;

-- 7. engine_manual_part_split: one part cut in two, no change of text
CREATE OR REPLACE FUNCTION public.engine_manual_part_split(p_part text, p_new_part text, p_new_title text, p_at text, p_base_version integer, p_base_md5 text, p_expect_md5_old text, p_expect_md5_new text, p_title text, p_summary text, p_log text, p_write boolean)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE v_base record; v_next numeric; v_oi numeric; v_max int; v_cnt int; v_pos int; v_keep text; v_move text;
        v_full_before text; v_full_after text; v_id1 bigint; v_id2 bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('engine_manual_version'));
  SELECT * INTO v_base FROM engine_manual_parts WHERE part = p_part ORDER BY version DESC LIMIT 1;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success',false,'error','no part '||coalesce(p_part,'null'));
  END IF;
  IF p_new_part IS NULL OR p_new_part !~ '^[0-9]{2}\.[0-9]+$' THEN
    RETURN jsonb_build_object('success',false,'error','new part name '||coalesce(p_new_part,'null')||' is not of the form 09.3');
  END IF;
  IF EXISTS (SELECT 1 FROM engine_manual_parts WHERE part = p_new_part) THEN
    RETURN jsonb_build_object('success',false,'error','part '||p_new_part||' exists');
  END IF;
  IF coalesce(btrim(p_new_title),'') = '' THEN
    RETURN jsonb_build_object('success',false,'error','the new part needs a title');
  END IF;
  IF p_base_version IS DISTINCT FROM v_base.version THEN
    RETURN jsonb_build_object('success',false,'error','base version '||coalesce(p_base_version::text,'null')||' is not part '||p_part||'''s latest version '||v_base.version);
  END IF;
  IF md5(v_base.content) IS DISTINCT FROM p_base_md5 THEN
    RETURN jsonb_build_object('success',false,'error','base md5 '||md5(v_base.content)||' is not '||coalesce(p_base_md5,'null'));
  END IF;
  IF p_at IS NULL OR p_at = '' THEN
    RETURN jsonb_build_object('success',false,'error','p_at is empty');
  END IF;
  v_cnt := (length(v_base.content) - length(replace(v_base.content, p_at, ''))) / length(p_at);
  IF v_cnt <> 1 THEN
    RETURN jsonb_build_object('success',false,'error','p_at occurs '||v_cnt||' times in part '||p_part||', not once');
  END IF;
  v_pos := strpos(v_base.content, p_at);
  IF v_pos = 1 THEN
    RETURN jsonb_build_object('success',false,'error','p_at starts the part; the part would be left empty');
  END IF;
  v_keep := left(v_base.content, v_pos - 1);
  v_move := substr(v_base.content, v_pos);
  SELECT min(order_index) INTO v_next FROM (SELECT DISTINCT ON (part) part, order_index FROM engine_manual_parts ORDER BY part, version DESC) l
    WHERE l.order_index > v_base.order_index;
  IF v_next IS NULL THEN v_oi := v_base.order_index + 100;
  ELSE v_oi := (v_base.order_index + v_next) / 2;
  END IF;
  SELECT greatest((SELECT max(version) FROM engine_manual), (SELECT max(version) FROM engine_manual_parts)) INTO v_max;
  IF NOT coalesce(p_write,false) THEN
    RETURN jsonb_build_object('success',true,'preview',true,'part',p_part,'new_part',p_new_part,'order_index_new',v_oi,
      'md5_old',md5(v_keep),'length_old',length(v_keep),'md5_new',md5(v_move),'length_new',length(v_move),
      'base_version',v_base.version,'next_version',v_max + 1);
  END IF;
  IF md5(v_keep) IS DISTINCT FROM p_expect_md5_old OR md5(v_move) IS DISTINCT FROM p_expect_md5_new THEN
    RETURN jsonb_build_object('success',false,'error','result md5s '||md5(v_keep)||' / '||md5(v_move)||' are not the expected '||coalesce(p_expect_md5_old,'null')||' / '||coalesce(p_expect_md5_new,'null'));
  END IF;
  IF coalesce(btrim(p_title),'') = '' OR coalesce(btrim(p_summary),'') = '' OR coalesce(btrim(p_log),'') = '' THEN
    RETURN jsonb_build_object('success',false,'error','title, summary and log are required to write');
  END IF;
  SELECT f.content INTO v_full_before FROM engine_manual_full() f;
  INSERT INTO engine_manual_parts (part, order_index, title, version, content, summary)
    VALUES (p_part, v_base.order_index, v_base.title, v_max + 1, v_keep, p_summary) RETURNING id INTO v_id1;
  INSERT INTO engine_manual_parts (part, order_index, title, version, content, summary)
    VALUES (p_new_part, v_oi, p_new_title, v_max + 1, v_move, p_summary) RETURNING id INTO v_id2;
  SELECT f.content INTO v_full_after FROM engine_manual_full() f;
  IF md5(v_full_before) IS DISTINCT FROM md5(v_full_after) THEN
    RAISE EXCEPTION 'engine_manual_part_split: the joined manual changed (% to %); nothing written', md5(v_full_before), md5(v_full_after);
  END IF;
  INSERT INTO engine_manual_log (version, entry_date, title, content, char_len, part)
    VALUES (v_max + 1, (now() at time zone 'America/Chicago')::date, p_title, p_log, length(v_keep), p_part);
  RETURN jsonb_build_object('success',true,'written',true,'ids',jsonb_build_array(v_id1,v_id2),'part',p_part,'new_part',p_new_part,
    'order_index_new',v_oi,'version',v_max + 1,'md5_old',md5(v_keep),'md5_new',md5(v_move),'md5_full',md5(v_full_after));
END; $function$;

