-- Objects: table engine_manual_parts (guard, audit trigger, grants, policies); column part on engine_manual_log;
-- functions engine_manual_part_apply, engine_manual_part_split, engine_manual_part, engine_manual_full, engine_manual_toc (rewritten);
-- engine_manual_apply replaced: refuses while engine_manual_parts holds a row, otherwise unchanged.
-- No COMMIT inside: the caller's transaction (apply_migration, or the rolled-back test) holds it.
-- The caller sets SET LOCAL truth.session_id (and truth.card for the write) first: the DDL audit trigger refuses without it.
-- Rules held here (plan draft 2c d0c99b47, W1 PASS Wall 11224; operator ruling at Wall 11221):
--  * No length limit anywhere: no check on content length, no refusal by size in part_apply or part_split.
--  * Part names match ^[0-9]{2}\.[0-9]+$ (for example 09.3, 09.81); any other name is refused (table check and part_split).
--  * order_index alone governs the order of the parts (engine_manual_full, engine_manual_toc); name order is not used.
--  * order_index is unique among the latest rows of different parts (guard, on every insert).
--  * order_index is numeric (plan draft 2c): part_split places the new part at the midpoint of the part and the next one,
--    which always exists, so splits at one place are not limited; after the last part it uses the part's order_index + 100.
--  * part_split refuses an empty piece (p_at at the very start of the part), an existing name, and a name off the pattern.
--  * p_title in part_apply and part_split is the title of the engine_manual_log row.

-- 1. Table
CREATE TABLE public.engine_manual_parts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part        text    NOT NULL CHECK (part ~ '^[0-9]{2}\.[0-9]+$'),
  order_index numeric NOT NULL,
  title       text    NOT NULL,
  version     integer NOT NULL,
  content     text    NOT NULL,
  summary     text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (part, version)
);
CREATE INDEX engine_manual_parts_part_version ON public.engine_manual_parts (part, version DESC);

-- 2. Guard and audit (insert only; every insert writes an audit row with card and session)
CREATE OR REPLACE FUNCTION public.engine_manual_parts_guard()
 RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'pg_temp'
AS $function$
BEGIN
  IF TG_OP IN ('UPDATE','DELETE','TRUNCATE') THEN
    RAISE EXCEPTION 'engine_manual_parts is insert-only. % blocked. To revise a part, call engine_manual_part_apply; to cut one in two, engine_manual_part_split.', TG_OP;
  END IF;
  -- C8: order_index is unique among the latest rows of different parts
  IF EXISTS (SELECT 1 FROM (SELECT DISTINCT ON (p.part) p.part, p.order_index FROM engine_manual_parts p
                            WHERE p.id <> NEW.id ORDER BY p.part, p.version DESC) l
             WHERE l.order_index = NEW.order_index AND l.part <> NEW.part) THEN
    RAISE EXCEPTION 'engine_manual_parts: order_index % is already held by another part', NEW.order_index;
  END IF;
  INSERT INTO audit_log (session_date, session_title, engine, notes)
  VALUES (CURRENT_DATE,
          'GUARD: engine_manual_parts ' || NEW.part || ' v' || NEW.version || ' inserted',
          'db-trigger',
          'AUTO-GUARD engine_manual_parts INSERT - part=' || NEW.part || ' version=' || NEW.version
          || ' order_index=' || NEW.order_index
          || ' hash=' || left(md5(NEW.content),12) || ' len=' || length(NEW.content)
          || ' | card=' || coalesce(left(nullif(btrim(current_setting('truth.card', true)), ''), 200), 'NONE')
          || ' | session=' || coalesce(left(nullif(btrim(current_setting('truth.session_id', true)), ''), 80), 'NONE')
          || ' | from=' || coalesce((SELECT 'v' || p.version || ' hash=' || left(md5(p.content),12) FROM engine_manual_parts p
                                     WHERE p.part = NEW.part AND p.version < NEW.version ORDER BY p.version DESC LIMIT 1), 'none')
          || '. This row is written by the trigger regardless of whether the editing model logged its own intent row.');
  RETURN NEW;
END;
$function$;
CREATE TRIGGER trg_engine_manual_parts_immutable BEFORE DELETE OR UPDATE ON public.engine_manual_parts
